#!/usr/bin/env python3
"""Generate the bounded R1033 assignment-statement policy."""

from pathlib import Path
import re
import sys


def main() -> int:
    source = Path(sys.argv[1]).read_text(encoding="utf-8").strip()
    match = re.fullmatch(
        r"\(schema frontend-assignment-policy-v0\s+"
        r"\(policy assignment-stmt assignment-stmt (R\d+)\)\s+"
        r"\(token assignment (=)\)\s+"
        r"\(expression integer-literal (1)\)\s+"
        r"\(binary-expression (add) (R\d+) (R\d+) (1) (2) (\+)\)\s+"
        r"\(binary-expression (multiply) (R\d+) (R\d+) (2) (3) (\*)\)\s+"
        r"\(binary-expression (divide) (R\d+) (R\d+) (6) (2) (/)\)\)", source
    )
    if match is None:
        raise SystemExit("invalid assignment policy schema")
    output = Path(sys.argv[2])
    output.mkdir(parents=True, exist_ok=True)
    (output / "frontend_assignment_policy_generated.f90").write_text(
        "! Generated by tools/generate_assignment_policy.py. Origin: MECHANICAL.\n"
        "module frontend_assignment_policy_generated\n"
        "    implicit none\n"
        "    private\n"
        "    character(len=*), parameter, public :: assignment_policy_lhs = 'assignment-stmt'\n"
        f"    character(len=*), parameter, public :: assignment_policy_source_rule = '{match.group(1)}'\n"
        "    character(len=*), parameter, public :: assignment_policy_operator = '='\n"
        "    character(len=*), parameter, public :: assignment_policy_integer_literal = '1'\n"
        f"    character(len=*), parameter, public :: assignment_policy_expression_kind = '{match.group(4)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_expression_rule = '{match.group(5)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_add_operator_rule = '{match.group(6)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_left_operand = '{match.group(7)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_right_operand = '{match.group(8)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_add_operator = '{match.group(9)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_multiply_expression_rule = '{match.group(11)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_multiply_operator_rule = '{match.group(12)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_multiply_left_operand = '{match.group(13)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_multiply_right_operand = '{match.group(14)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_multiply_operator = '{match.group(15)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_divide_expression_rule = '{match.group(17)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_divide_operator_rule = '{match.group(18)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_divide_left_operand = '{match.group(19)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_divide_right_operand = '{match.group(20)}'\n"
        f"    character(len=*), parameter, public :: assignment_policy_divide_operator = '{match.group(21)}'\n"
        "    integer, parameter, public :: assignment_policy_source_page = 155\n"
        "end module frontend_assignment_policy_generated\n",
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
