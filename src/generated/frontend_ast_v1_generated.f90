    subroutine generated_ast_kind_count(value, kind, count, ok, message)
        class(*), optional, intent(in) :: value
        character(len=*), intent(in) :: kind
        integer(int64), intent(out) :: count
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message

        count = 0_int64
        ok = .false.
        message = ''
        if (len_trim(kind) == 0) then
            message = 'empty-generated-record-kind'
            return
        end if
        if (.not. present(value)) then
            ok = .true.
            return
        end if
        select type (value)
            type is (source_span_t)
            call generated_ast_count_source_span(kind, count)
            ok = .true.
            type is (program_root_t)
            call generated_ast_count_program_root(kind, count)
            ok = .true.
            type is (program_declaration_t)
            call generated_ast_count_program_declaration(kind, count)
            ok = .true.
            type is (variable_declaration_t)
            call generated_ast_count_variable_declaration(kind, count)
            ok = .true.
            type is (assignment_expression_t)
            call generated_ast_count_assignment_expression(kind, count)
            ok = .true.
            type is (assignment_stmt_t)
            call generated_ast_count_assignment_stmt(kind, count)
            ok = .true.
            type is (program_unit_t)
            call generated_ast_count_program_unit(kind, count)
            ok = .true.
        class default
            message = 'unsupported-generated-record-kind-query'
        end select
    end subroutine generated_ast_kind_count

    logical function generated_valid_atom(value)
        character(len=*), intent(in) :: value
        integer :: index

        generated_valid_atom = .false.
        if (len_trim(value) == 0) return
        do index = 1, len_trim(value)
            if (value(index:index) == ' ' .or. value(index:index) == achar(9) .or. &
                value(index:index) == '(' .or. value(index:index) == ')') return
        end do
        generated_valid_atom = .true.
    end function generated_valid_atom

    subroutine generated_copy_text(text, output, ok, message)
        character(len=*), intent(in) :: text
        character(len=*), intent(out) :: output
        logical, intent(out) :: ok
        character(len=*), intent(out) :: message
        integer :: text_length

        text_length = len_trim(text)
        if (text_length > len(output)) then
            output = ''
            ok = .false.
            message = 'sx-output-too-short'
            return
        end if
        output = ''
        if (text_length > 0) output(:text_length) = text(:text_length)
        ok = .true.
        message = ''
    end subroutine generated_copy_text
